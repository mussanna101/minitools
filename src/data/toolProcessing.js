export function getToolProcessingProfile(toolOrId) {
  const id = typeof toolOrId === 'string' ? toolOrId : toolOrId?.id;
  return PROFILES[id] || LOCAL_PROFILE;
}

export function getToolProcessingKind(toolOrId) {
  return getToolProcessingProfile(toolOrId).kind;
}

export function getProcessingProfileIds() {
  return Object.keys(PROFILES);
}
