// scripts/submit-indexnow.mjs
// Submits the full site URL inventory to Bing/DuckDuckGo via IndexNow for fast
// indexing. Run MANUALLY (not hooked into every build, to avoid spamming):
//   node scripts/submit-indexnow.mjs
//
// Requirements:
//   - The key file public/<KEY>.txt must exist and be deployed.
//   - All URLs are read from public/indexnow-urls.txt (the single canonical
//     inventory of every indexable URL: 1 homepage + 8 categories + 88 tools).

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const HOST = 'minitools-silk.vercel.app';
const KEY = '80895b70cacd3fb9303a4f4a1c82d51c';
const SITE = `https://${HOST}`;

// Read the canonical URL list (regenerated by public/indexnow-urls.txt before
// every build via the sitemap generator; keep this file in sync).
const urlsFile = join(__dirname, '..', 'public', 'indexnow-urls.txt');
const urlList = readFileSync(urlsFile, 'utf8')
  .split(/\r?\n/)
  .map((u) => u.trim())
  .filter((u) => u.startsWith(SITE));

if (urlList.length === 0) {
  console.error('No URLs found in public/indexnow-urls.txt');
  process.exit(1);
}

const body = {
  host: HOST,
  key: KEY,
  keyLocation: `${SITE}/${KEY}.txt`,
  urlList,
};

try {
  const resp = await fetch('https://api.indexnow.org/indexnow', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json; charset=utf-8' },
    body: JSON.stringify(body),
  });
  console.log(`IndexNow HTTP ${resp.status} — ${urlList.length} URLs submitted`);
  const text = await resp.text();
  if (!resp.ok) console.log(text.slice(0, 500));
  process.exit(resp.ok ? 0 : 1);
} catch (err) {
  console.error('IndexNow submission failed (network error):', err.message);
  process.exit(1);
}
